// Bundle the generate-plan-day Edge function into a self-contained index.ts.
//
// Supabase Edge deploy does NOT bundle files outside the function directory,
// so the function's `@/` imports into the shared app source (../../../src/)
// fail at runtime. This pre-bundles the whole graph into one Deno-target file
// with only `npm:` and `node:` specifiers left external (both native to Deno).
//
//   npm run build:edge-function   →  supabase/functions/generate-plan-day/index.ts
//
// Edit entry.ts (the source); index.ts is generated + committed (like the
// lexicon indexes) so deploys are reproducible.
import * as esbuild from 'esbuild'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const fnDir = path.join(root, 'supabase/functions/generate-plan-day')

// Node builtins Deno provides natively — keep external (string-exact, so
// esbuild never tries to resolve/bundle them).
const NODE_BUILTINS = [
  'fs',
  'path',
  'url',
  'crypto',
  'buffer',
  'stream',
  'util',
  'os',
  'events',
]
const nodeExternal = NODE_BUILTINS.map((m) => `node:${m}`)
// Alias bare builtins (`import fs from 'fs'`) to their node: form so they hit
// the external list too.
const bareAlias = Object.fromEntries(NODE_BUILTINS.map((m) => [m, `node:${m}`]))

const denoResolve = {
  name: 'deno-resolve',
  setup(build) {
    // brain router → the direct-Anthropic shim
    build.onResolve({ filter: /^@\/lib\/brain\/router$/ }, () => ({
      path: path.join(fnDir, 'brain-direct.ts'),
    }))
    // OpenNext context → the throwing stub (loaders fall through to self-fetch)
    build.onResolve({ filter: /^@opennextjs\/cloudflare$/ }, () => ({
      path: path.join(fnDir, 'opennext-stub.ts'),
    }))
    // @/ → the app's src/ tree
    build.onResolve({ filter: /^@\// }, (a) => ({
      path: path.join(root, 'src', a.path.slice(2)),
    }))
  },
}

await esbuild.build({
  entryPoints: [path.join(fnDir, 'entry.ts')],
  outfile: path.join(fnDir, 'index.ts'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'esnext',
  // Keep node: builtins AND @supabase/supabase-js external. The latter stays a
  // bare specifier in the output; deno.json's import map rewrites it to
  // `npm:@supabase/supabase-js@2` at runtime (Deno resolves npm: natively),
  // which avoids bundling its Node build (realtime-js/auth-js/functions-js).
  external: [...nodeExternal, '@supabase/supabase-js'],
  alias: bareAlias,
  resolveExtensions: ['.ts', '.tsx', '.mjs', '.js', '.json'],
  legalComments: 'none',
  logLevel: 'info',
  banner: {
    js: '// AUTO-GENERATED by scripts/build-edge-function.mjs — DO NOT EDIT.\n// Edit entry.ts and run `npm run build:edge-function`.',
  },
})
console.log('✓ bundled → supabase/functions/generate-plan-day/index.ts')
