#!/usr/bin/env node
/**
 * Audit T2 (HOMEPAGE-AUDIT-2026-05-11): generate a build-time teaser
 * index so generateMetadata can produce per-day meta descriptions in
 * the Cloudflare Workers runtime, where fs.readFile against public/
 * does not resolve (public/* files are bound as ASSETS, not present
 * on the Worker filesystem).
 *
 * Output: src/data/devotional-teasers.ts — a plain TS module that
 * exports a Record<slug, teaser> built from every JSON in
 * public/devotionals/. Run by `npm run build` via the build pipeline.
 */
import { promises as fs } from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const devDir = path.join(root, 'public', 'devotionals')
const outFile = path.join(root, 'src', 'data', 'devotional-teasers.ts')

async function main() {
  const files = (await fs.readdir(devDir)).filter((f) => f.endsWith('.json'))
  const entries = []
  for (const file of files) {
    try {
      const raw = await fs.readFile(path.join(devDir, file), 'utf-8')
      const data = JSON.parse(raw)
      const slug = file.replace(/\.json$/, '')
      const teaser = typeof data.teaser === 'string' ? data.teaser.trim() : ''
      if (teaser) entries.push([slug, teaser])
    } catch {
      // Skip malformed JSON; we still get a valid index.
    }
  }
  entries.sort(([a], [b]) => a.localeCompare(b))

  const lines = [
    '// AUTO-GENERATED by scripts/generate-devotional-teasers.mjs',
    "// Do not edit by hand. Re-run via `npm run build` (or the script directly).",
    '',
    'export const DEVOTIONAL_TEASERS: Record<string, string> = {',
    ...entries.map(([slug, teaser]) => {
      const safe = teaser.replace(/\\/g, '\\\\').replace(/'/g, "\\'")
      return `  '${slug}': '${safe}',`
    }),
    '}',
    '',
    'export function getDevotionalTeaser(slug: string): string | null {',
    '  const t = DEVOTIONAL_TEASERS[slug]',
    '  return t && t.length > 0 ? t : null',
    '}',
    '',
  ]
  await fs.writeFile(outFile, lines.join('\n'), 'utf-8')
  console.log(
    `[devotional-teasers] Wrote ${entries.length} teasers to ${path.relative(root, outFile)}`,
  )
}

main().catch((err) => {
  console.error('[devotional-teasers] Failed:', err)
  process.exit(1)
})
