#!/usr/bin/env node
/**
 * Audit T2 (HOMEPAGE-AUDIT-2026-05-11): generate a build-time
 * devotional metadata index so generateMetadata can produce per-day
 * <title> + <meta description> in the Cloudflare Workers runtime,
 * where fs.readFile against public/ does not resolve (public/* files
 * are bound as ASSETS, not present on the Worker filesystem).
 *
 * Output: src/data/devotional-teasers.ts — exports a Record<slug,
 * teaser> AND a Record<slug, title> built from every JSON in
 * public/devotionals/. Run by `npm run build` via the build pipeline.
 *
 * 2026-05-13: extended to capture `title` so article page titles can
 * use the headline (e.g. "A Voice in the Wilderness") instead of
 * the bare "Day N" placeholder stored in series.ts.
 */
import { promises as fs } from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const devDir = path.join(root, 'public', 'devotionals')
const outFile = path.join(root, 'src', 'data', 'devotional-teasers.ts')

function escapeSingle(s) {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")
}

async function main() {
  const files = (await fs.readdir(devDir)).filter((f) => f.endsWith('.json'))
  const teaserEntries = []
  const titleEntries = []
  for (const file of files) {
    try {
      const raw = await fs.readFile(path.join(devDir, file), 'utf-8')
      const data = JSON.parse(raw)
      const slug = file.replace(/\.json$/, '')
      const teaser = typeof data.teaser === 'string' ? data.teaser.trim() : ''
      const title = typeof data.title === 'string' ? data.title.trim() : ''
      if (teaser) teaserEntries.push([slug, teaser])
      if (title) titleEntries.push([slug, title])
    } catch {
      // Skip malformed JSON; we still get a valid index.
    }
  }
  teaserEntries.sort(([a], [b]) => a.localeCompare(b))
  titleEntries.sort(([a], [b]) => a.localeCompare(b))

  const lines = [
    '// AUTO-GENERATED by scripts/generate-devotional-teasers.mjs',
    "// Do not edit by hand. Re-run via `npm run build` (or the script directly).",
    '',
    'export const DEVOTIONAL_TEASERS: Record<string, string> = {',
    ...teaserEntries.map(
      ([slug, teaser]) => `  '${slug}': '${escapeSingle(teaser)}',`,
    ),
    '}',
    '',
    'export const DEVOTIONAL_TITLES: Record<string, string> = {',
    ...titleEntries.map(
      ([slug, title]) => `  '${slug}': '${escapeSingle(title)}',`,
    ),
    '}',
    '',
    'export function getDevotionalTeaser(slug: string): string | null {',
    '  const t = DEVOTIONAL_TEASERS[slug]',
    '  return t && t.length > 0 ? t : null',
    '}',
    '',
    'export function getDevotionalTitle(slug: string): string | null {',
    '  const t = DEVOTIONAL_TITLES[slug]',
    '  return t && t.length > 0 ? t : null',
    '}',
    '',
  ]
  await fs.writeFile(outFile, lines.join('\n'), 'utf-8')
  console.log(
    `[devotional-teasers] Wrote ${teaserEntries.length} teasers + ${titleEntries.length} titles to ${path.relative(root, outFile)}`,
  )
}

main().catch((err) => {
  console.error('[devotional-teasers] Failed:', err)
  process.exit(1)
})
